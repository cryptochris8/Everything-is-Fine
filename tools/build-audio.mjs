// Bakes the game's music, sound effects and voice lines to MP3 with ElevenLabs, once, at
// build time (the method from Fable-5.1-one-shot/tools/build-audio.mjs). Nothing calls
// ElevenLabs at runtime: no key in the game, no per-play cost.
//
//   ELEVENLABS_API_KEY=... node tools/build-audio.mjs [--only=music|sfx|voice] [--id=<id>] [--force] [--dry]
//
// Idempotent: a file that already exists is kept (and never billed again) unless --force.
// --dry lists what would be generated and the characters/seconds it would spend.
// After any run it rewrites src/game/audioManifest.ts: LITERAL @project/assets paths (Studio
// ships only literal strings it finds in the bundle) plus the voice-line index.
import fs from 'node:fs/promises';
import fss from 'node:fs';
import path from 'node:path';

import { MUSIC, SFX, VOICES, voiceLines } from './audio-catalog.mjs';

const KEY = process.env.ELEVENLABS_API_KEY;
const DRY = process.argv.includes('--dry');
if (!KEY && !DRY) {
  console.error('ELEVENLABS_API_KEY not set');
  process.exit(1);
}
const H = { 'xi-api-key': KEY ?? '', 'content-type': 'application/json' };
const OUT = 'assets/audio';
const FORCE = process.argv.includes('--force');
const ONLY = (process.argv.find((a) => a.startsWith('--only=')) ?? '').slice(7);
const ID = (process.argv.find((a) => a.startsWith('--id=')) ?? '').slice(5);
const want = (kind, id) => (!ONLY || ONLY === kind) && (!ID || ID === id);
const exists = (rel) => fss.existsSync(path.join(OUT, rel));

let made = 0;
let skipped = 0;
let failed = 0;
let chars = 0;
let seconds = 0;

async function save(rel, bytes) {
  const p = path.join(OUT, rel);
  await fs.mkdir(path.dirname(p), { recursive: true });
  await fs.writeFile(p, bytes);
}

async function req(url, body, label) {
  for (let attempt = 1; attempt <= 3; attempt++) {
    const r = await fetch(url, { method: 'POST', headers: H, body: JSON.stringify(body) });
    if (r.ok) {
      return Buffer.from(await r.arrayBuffer());
    }
    const txt = await r.text();
    if (r.status === 429 || r.status >= 500) {
      await new Promise((s) => setTimeout(s, 2000 * attempt));
      continue;
    }
    throw new Error(`${r.status} ${txt.slice(0, 240)}`);
  }
  throw new Error('retries exhausted for ' + label);
}

async function job(kind, rel, label, cost, fn) {
  if (!FORCE && exists(rel)) {
    skipped++;
    return;
  }
  if (DRY) {
    console.log(`  would make ${rel}  (${label})`);
    cost();
    return;
  }
  try {
    const buf = await fn();
    await save(rel, buf);
    made++;
    cost();
    console.log(`  made ${rel}  ${(buf.length / 1024).toFixed(0)} KB`);
  } catch (e) {
    failed++;
    console.error(`  FAIL ${rel}: ${e.message}`);
  }
}

// ---------------------------------------------------------------- music -----
for (const [id, m] of Object.entries(MUSIC)) {
  if (!want('music', id)) continue;
  await job('music', `music/${id}.mp3`, `${m.seconds}s music`, () => (seconds += m.seconds), () =>
    req('https://api.elevenlabs.io/v1/music?output_format=mp3_44100_128', { prompt: m.prompt, music_length_ms: m.seconds * 1000 }, id),
  );
}

// ------------------------------------------------------------------ sfx -----
for (const [id, s] of Object.entries(SFX)) {
  if (!want('sfx', id)) continue;
  await job('sfx', `sfx/${id}.mp3`, `${s.seconds}s sfx`, () => (seconds += s.seconds), () =>
    req('https://api.elevenlabs.io/v1/sound-generation?output_format=mp3_44100_96', { text: s.prompt, duration_seconds: s.seconds, prompt_influence: 0.6, loop: !!s.loop }, id),
  );
}

// ---------------------------------------------------------------- voice -----
const lines = voiceLines();
for (const l of lines) {
  if (!want('voice', l.id)) continue;
  const v = VOICES[l.speaker];
  await job('voice', `voice/${l.id}.mp3`, `${l.speaker}: ${l.text.length} chars`, () => (chars += l.text.length), () =>
    req(
      `https://api.elevenlabs.io/v1/text-to-speech/${v.id}?output_format=mp3_44100_64`,
      { text: l.spoken ?? l.text, model_id: 'eleven_multilingual_v2', voice_settings: { stability: v.stability ?? 0.4, similarity_boost: 0.8, style: v.style ?? 0.45, use_speaker_boost: true } },
      l.id,
    ),
  );
}

// ------------------------------------------------------------- manifest -----
const have = (rel) => fss.existsSync(path.join(OUT, rel));
const lit = (rel) => `'@project/assets/audio/${rel}'`;
const musicIds = Object.keys(MUSIC).filter((id) => have(`music/${id}.mp3`));
const sfxIds = Object.keys(SFX).filter((id) => have(`sfx/${id}.mp3`));
const voiced = lines.filter((l) => have(`voice/${l.id}.mp3`));
const ts = `/**
 * GENERATED by tools/build-audio.mjs — do not edit. Every path is a LITERAL string so the
 * Studio build (which ships only literal @project paths found in the bundle) includes it.
 */
export const MUSIC_FILES: Readonly<Record<string, string>> = {
${musicIds.map((id) => `  ${id}: ${lit(`music/${id}.mp3`)},`).join('\n')}
};

export const SFX_FILES: Readonly<Record<string, string>> = {
${sfxIds.map((id) => `  ${id}: ${lit(`sfx/${id}.mp3`)},`).join('\n')}
};

/** Voice lines: speaker + exact on-screen text → file. */
export const VOICE_LINES: readonly { speaker: string; text: string; file: string }[] = [
${voiced.map((l) => `  { speaker: ${JSON.stringify(l.speaker)}, text: ${JSON.stringify(l.text)}, file: ${lit(`voice/${l.id}.mp3`)} },`).join('\n')}
];
`;
if (!DRY) {
  await fs.writeFile('src/game/audioManifest.ts', ts);
}
console.log(`\n${DRY ? 'DRY RUN: ' : ''}made ${made}, kept ${skipped}, failed ${failed} · ${chars} voice chars · ${seconds}s music+sfx` + (DRY ? '' : `\nmanifest: ${musicIds.length} music, ${sfxIds.length} sfx, ${voiced.length}/${lines.length} voice lines`));
